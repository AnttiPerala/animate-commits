import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, writeFile, rm } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import net from 'node:net';
import { createGuiServer } from '../src/gui.js';
import { launchBrowser } from '../src/browser.js';
import { git } from '../src/git.js';

test('graphical interface inspects, captures, previews and reports errors', { timeout: 120000 }, async () => {
  const temp = await mkdtemp(join(tmpdir(), 'animate-gui-test-'));
  const opened = [];
  const app = await createGuiServer({ historyFile: join(temp, 'preferences', 'recent.json'), folderOpener: async folder => {
    if (folder === 'missing-output') throw new Error('Output folder does not exist');
    opened.push(folder); return folder;
  } });
  const browser = await launchBrowser();
  try {
    await git(['init', '.'], temp); await git(['config', 'user.name', 'Fixture'], temp); await git(['config', 'user.email', 'fixture@example.invalid'], temp);
    for (const [message, color] of [['First UI', 'tomato'], ['Second UI', 'steelblue']]) {
      await writeFile(join(temp, 'index.html'), `<body style="background:${color}"><h1>${message}</h1></body>`);
      await git(['add', '.'], temp); await git(['commit', '-m', message], temp);
    }
    const page = await browser.newPage({ viewport: { width: 1320, height: 1000 } });
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.goto(app.url);
    await page.waitForFunction(() => document.getElementById('width').value === '1920');
    await mkdir(resolve('captures/gui'), { recursive: true });
    await page.screenshot({ path: resolve('captures/gui/interface.png'), fullPage: true });
    await page.locator('#repo').fill(temp);
    await page.locator('#output').fill(join(temp, 'output'));
    await page.locator('#openOutput').click();
    await page.waitForFunction(() => document.getElementById('openOutput').textContent === 'Open output folder');
    assert.deepEqual(opened, [join(temp, 'output')]);
    await page.locator('#output').fill('missing-output');
    await page.locator('#openOutput').click();
    await page.waitForFunction(() => document.getElementById('error').textContent.includes('Output folder does not exist'));
    await page.locator('#output').fill(join(temp, 'output'));
    await page.locator('#width').fill('640'); await page.locator('#height').fill('360');
    const portServer = net.createServer();
    await new Promise(resolve => portServer.listen(0, '127.0.0.1', resolve));
    const port = portServer.address().port;
    await new Promise(resolve => portServer.close(resolve));
    await page.locator('summary').click();
    await page.locator('#port').fill(String(port));
    await page.locator('summary').click();
    await page.locator('#inspect').click();
    await page.waitForFunction(() => document.getElementById('status').textContent === 'History ready', { }, { timeout: 30000 });
    assert.equal(await page.locator('#commits li').count(), 2);
    assert.equal(await page.locator('#recentRepos option').count(), 2);
    await page.locator('#repo').fill('');
    await page.locator('#recentRepos').selectOption(temp);
    assert.equal(await page.locator('#repo').inputValue(), temp);
    await page.locator('#capture').click();
    await page.waitForFunction(() => document.getElementById('status').textContent === 'Capture complete', { }, { timeout: 60000 });
    assert.equal(await page.locator('#frameCount').textContent(), '2 FRAMES · 0 FAILED');
    await page.locator('#latest').evaluate(img => img.decode());
    await page.locator('#preview').click();
    const preview = page.frameLocator('#previewFrame');
    await preview.locator('#next').click();
    assert.equal(await preview.locator('#message').textContent(), 'Second UI');
    await page.locator('#closePreview').click();
    await page.screenshot({ path: resolve('captures/gui/completed.png'), fullPage: true });
    await page.locator('#capture').click();
    await page.waitForFunction(() => document.getElementById('status').textContent === 'Capture failed', { }, { timeout: 15000 });
    assert.match(await page.locator('#error').textContent(), /must be empty/);
    await writeFile(join(temp, 'index.html'), '<h1>Third UI</h1>');
    await git(['add', 'index.html'], temp); await git(['commit', '-m', 'Third UI'], temp);
    await page.locator('#update').check();
    assert.equal(await page.locator('#capture').textContent(), 'Update capture');
    await page.locator('#capture').click();
    await page.waitForFunction(() => document.getElementById('status').textContent === 'Capture complete', {}, { timeout: 60000 });
    assert.equal(await page.locator('#frameCount').textContent(), '3 FRAMES · 0 FAILED');
    await page.locator('#capture').click();
    await page.waitForFunction(() => document.getElementById('status').textContent === 'Already up to date', {}, { timeout: 30000 });
    await page.screenshot({ path: resolve('captures/gui/updated.png'), fullPage: true });
    await page.locator('#update').uncheck();
    await page.locator('#appType').selectOption('native');
    assert.equal(await page.locator('#nativeWindowTitle').isVisible(), true);
    assert.equal(await page.locator('#url').isVisible(), false);
    await page.locator('#appType').selectOption('web');
    await page.locator('#output').fill(join(temp, 'cancelled-output'));
    await page.locator('summary').click();
    await page.locator('#delay').fill('30000');
    await page.locator('#capture').click();
    await page.waitForFunction(() => document.getElementById('logs').textContent.includes('[1/3]'), {}, { timeout: 30000 });
    await page.locator('#stop').click();
    await page.waitForFunction(() => document.getElementById('status').textContent === 'Cancelled', {}, { timeout: 30000 });
    assert.equal(await page.locator('#capture').isEnabled(), true);
    assert.deepEqual(errors, []);
    const unauthorized = await fetch(new URL('/api/state', app.url));
    assert.equal(unauthorized.status, 404);
    const crossOrigin = await fetch(new URL('api/start', app.url), { method: 'POST', headers: { Origin: 'https://example.com', 'Content-Type': 'application/json' }, body: '{}' });
    assert.equal(crossOrigin.status, 403);
  } finally { await browser.close(); await app.close(); await rm(temp, { recursive: true, force: true, maxRetries: 3 }); }
});
